"""Build the report PDF from report/final_report.md. OWNER: Jagdeesh.

Run from the repo root:  python report/build_pdf.py
Needs pandoc and a Chrome/Chromium binary (--chromium, default: "chromium" on PATH;
on Windows e.g. "C:/Program Files/Google/Chrome/Application/chrome.exe").
Writes report/final/PathSnap_report.html and report/final/PathSnap_report.pdf.

The figures appendix embeds plots that the scripts wrote into results/ (nothing is drawn
here), so every figure in the PDF is a real experiment output. Folium maps are interactive
HTML; add their screenshots as PNGs under report/final/screenshots/ and they are appended too.
"""
import argparse
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "report" / "final"

FIGURES = [
    ("results/eda/sampling_hist.png", "EDA (train): sampling intervals"),
    ("results/eda/network_size.png", "EDA (train): road-network size per trip"),
    ("results/eda/trajectories.png", "EDA (train): GPS trajectories"),
    ("results/models/plots/cv_top1.png", "Cross-validation Top-1, 5 models (GroupKFold by trip, train)"),
    ("results/models/plots/cv_f1_macro.png", "Cross-validation macro F1, 5 models"),
    ("results/models/plots/cv_log_loss.png", "Cross-validation log loss, 5 models"),
    ("results/models/plots/student_test_top1_f1.png", "Student-test Top-1 and macro F1 (one final run)"),
    ("results/models/plots/student_test_log_loss.png", "Student-test log loss (one final run)"),
    ("results/models/plots/loss_curve_lightgbm.png", "LightGBM training history (CV fold 0)"),
    ("results/models/plots/loss_curve_lightgbm_tuned.png", "Tuned LightGBM training history (CV fold 0)"),
    ("results/models/plots/loss_curve_mlp.png", "MLP training history (CV fold 0)"),
    ("results/models/plots/optuna_history.png", "Optuna optimisation history (40 trials)"),
    ("results/models/plots/optuna_param_importance.png", "Optuna hyperparameter importance"),
    ("results/models/plots/confusion_lightgbm_tuned.png", "Confusion matrix, tuned LightGBM, student_test"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--chromium", default="chromium", help="Chrome/Chromium binary")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    body = subprocess.run(["pandoc", str(ROOT / "report" / "final_report.md"), "-t", "html"],
                          check=True, capture_output=True, text=True).stdout
    figs = []
    for path, cap in FIGURES:
        p = ROOT / path
        if p.exists():
            figs.append(f'<figure><img src="{p.as_uri()}"><figcaption>{cap} '
                        f'(<code>{path}</code>)</figcaption></figure>')
    shots = sorted((OUT / "screenshots").glob("*.png")) if (OUT / "screenshots").exists() else []
    for p in shots:
        figs.append(f'<figure><img src="{p.as_uri()}"><figcaption>{p.stem}</figcaption></figure>')
    html = f"""<!doctype html><html><head><meta charset="utf-8"><title>PathSnap report</title>
<style>body{{font-family:Georgia,serif;max-width:820px;margin:auto;line-height:1.45;font-size:11pt}}
table{{border-collapse:collapse;font-size:9pt}}td,th{{border:1px solid #999;padding:3px 5px}}
code{{font-size:9pt}}figure{{page-break-inside:avoid;margin:18px 0}}img{{max-width:100%}}
figcaption{{font-size:9pt;color:#444}}</style></head><body>
{body}<h2>Appendix: figures (generated by the scripts, unedited)</h2>{''.join(figs)}</body></html>"""
    html_path = OUT / "PathSnap_report.html"
    html_path.write_text(html, encoding="utf-8")
    pdf = OUT / "PathSnap_report.pdf"
    subprocess.run([a.chromium, "--headless", "--no-sandbox", "--disable-gpu",
                    "--no-pdf-header-footer", f"--print-to-pdf={pdf}", html_path.as_uri()],
                   check=True, capture_output=True)
    print(f"Wrote {OUT / 'PathSnap_report.pdf'} ({len(figs)} figures)")


if __name__ == "__main__":
    main()
